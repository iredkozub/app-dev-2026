"""Решение агента для задачи Valid Parentheses (LeetCode #20).

Почему выбран стек:
Закрывающая скобка должна соответствовать последней ещё не закрытой
открывающей скобке. Это порядок LIFO (Last In, First Out), поэтому
для хранения открывающих скобок подходит стек.

В Python стек удобно реализовать списком: append() добавляет элемент
на вершину, pop() удаляет последний добавленный элемент.

Оценка сложности:
- Время: O(n), где n — длина строки. Мы проходим строку один раз;
  каждую скобку добавляем в стек и удаляем из него не более одного раза.
  Операции append() и pop() с конца списка выполняются за O(1)
  амортизированно.
- Дополнительная память: O(n) в худшем случае, например для строки,
  состоящей только из открывающих скобок. Словарь из трёх пар занимает
  O(1), но стек может вырасти до n элементов.
"""


class Solution:
    def isValid(self, s: str) -> bool:
        stack = []
        brackets = {"(": ")", "[": "]", "{": "}"}

        for char in s:
            if char in brackets:
                # Открывающую скобку сохраняем до появления её пары.
                stack.append(char)
            else:
                # Закрывающая скобка должна соответствовать вершине стека.
                if not stack or brackets[stack.pop()] != char:
                    return False

        # Если стек не пуст, часть открывающих скобок осталась без пары.
        return not stack
